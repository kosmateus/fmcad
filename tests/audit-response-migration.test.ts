function directory(t: test.TestContext): string {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "audit-response-parity-"));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  return dir;
}
test("response proof preserves the complete original manifest and refuses changed, escaped or invented evidence", (t) => {
  const dir = directory(t),
    audit = path.join(dir, "jobs", "target", "atomic-recovery-audit"),
    migration = path.join(dir, "migration");
  fs.mkdirSync(audit, { recursive: true });
  fs.mkdirSync(migration);
  const remote = path.join(audit, "remote.json");
  for (const name of ["intent", "wire", "result"])
    fs.writeFileSync(path.join(audit, name + ".json"), "{}");
  for (const name of ["intent", "complete"])
    fs.writeFileSync(path.join(migration, name + ".json"), "{}");
  fs.writeFileSync(
    remote,
    JSON.stringify({ terminal: true, outcome: "succeeded" }),
  );
  fs.writeFileSync(
    path.join(audit, "start.json"),
    JSON.stringify({ receipt: remote }),
  );
  const scope = { jobId: "target", observationJobId: "observer" };
  const manifests = proofs.map((api) =>
    api.collectAuditResponseFiles(dir, migration, scope),
  );
  assert.deepEqual(manifests[1], manifests[0]);
  for (const api of proofs) {
    assert.equal(
      api.auditResponseProofStillCurrent({ files: manifests[0] }),
      true,
    );
    assert.throws(
      () => api.auditResponseProof(manifests[0], dir, scope),
      { code: "AUDIT_RESPONSE_PROOF_INVALID" },
      "A successful physical receipt alone never invents migration ownership or dynamic facts",
    );
  }
  const before = fs.readdirSync(audit).sort();
  fs.appendFileSync(remote, "\n");
  for (const api of proofs) {
    assert.equal(
      api.auditResponseProofStillCurrent({ files: manifests[0] }),
      false,
    );
    assert.throws(() => api.auditResponseProof(manifests[0], dir, scope), {
      code: "AUDIT_RESPONSE_PROOF_INVALID",
    });
  }
  assert.deepEqual(fs.readdirSync(audit).sort(), before);
  fs.writeFileSync(
    path.join(audit, "start.json"),
    JSON.stringify({ receipt: path.join(dir, "foreign.json") }),
  );
  for (const api of proofs)
    assert.throws(() => api.collectAuditResponseFiles(dir, migration, scope), {
      code: "AUDIT_RESPONSE_PROOF_INVALID",
    });
});
test("facts capture keeps every source unit, generated byte, provenance hash and exact broker path", (t) => {
  const restore = (
    load("./tests/fixtures/fake-wsl-platform.cjs") as () => () => void
  )();
  t.after(restore);
  const dir = directory(t),
    binding = {
      purpose: "atomic-recovery-audit-facts-capture-v1",
      originalRpcId: "original",
      originalEvidenceHash: "a".repeat(64),
      captureProofPath: path.join(dir, "sdk-facts.json"),
      currentInstance: { pid: 7, birth: "synthetic:7", version: "2706" },
    };
  const identity = {
    commandId: "fmcad_atomic_original",
    resolvedIdentity: {
      name: "Żółta część",
      creationId: "original-id",
      fileId: null,
    },
  };
  const values = captures.map((api) =>
    api.prepareAuditFactsCapture(root, identity, binding, { directory: dir }),
  );
  assert.deepEqual(values[1], values[0]);
  assert.equal(
    values[1]!.artifact.units.filter((unit) => unit.role === "runtime").length,
    2,
  );
  assert.equal(
    fs.existsSync(binding.captureProofPath),
    false,
    "Preparation cannot execute the observation",
  );
  for (const api of captures)
    assert.throws(
      () =>
        api.prepareAuditFactsCapture(
          root,
          identity,
          { ...binding, captureProofPath: path.join(dir, "foreign.json") },
          { directory: dir },
        ),
      { code: "INVALID_CAPTURE_PATH" },
    );
});
test("facts CLI checks capability and exact build before forwarding the original authenticated control", async () => {
  const outputs: unknown[] = [];
  for (const api of captures) {
    const calls: unknown[] = [];
    let status: Record<string, unknown> = { features: {} };
    const client = {
      async call(action: string, input?: unknown) {
        calls.push({ action, input });
        return action === "queue-summary" ? status : { observed: true };
      },
    };
    await assert.rejects(
      api.auditFactsAction(client, "capture-audit-facts", {}, "build"),
      { code: "AUDIT_CAPTURE_UNSUPPORTED" },
    );
    status = {
      features: { auditFactsCapture: true },
      control: {
        buildHash: "foreign",
        instanceId: "owner",
        generation: 3,
        contextEpoch: 4,
      },
    };
    await assert.rejects(
      api.auditFactsAction(client, "capture-audit-facts", {}, "build"),
      { code: "BUILD_CHANGED" },
    );
    status = {
      features: { auditFactsCapture: true },
      control: {
        buildHash: "build",
        instanceId: "owner",
        generation: 3,
        contextEpoch: 4,
      },
    };
    const result = await api.auditFactsAction(
      client,
      "capture-audit-facts",
      { requestId: "original", confirmReadOnly: true },
      "build",
    );
    outputs.push({ calls, result });
    assert.equal(
      calls.length,
      4,
      "Only the final qualified attempt dispatches an action",
    );
  }
  assert.deepEqual(outputs[1], outputs[0]);
});
