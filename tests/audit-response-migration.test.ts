function current(name: string): unknown {
  const filename = path.join(root, `src/${name}.js`);
  const module = new Module(filename) as Module & {
    _compile(source: string, filename: string): void;
  };
  module.filename = filename;
  module.paths = createRequire(filename).resolve.paths("fixture") ?? [];
  module._compile(
    ts.transpileModule(
      fs.readFileSync(path.join(root, `src/${name}.ts`), "utf8"),
      {
        compilerOptions: {
          module: ts.ModuleKind.CommonJS,
          target: ts.ScriptTarget.ES2023,
        },
      },
    ).outputText,
    filename,
  );
  return module.exports as unknown;
}
