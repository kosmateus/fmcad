type HttpRpcParams = {
  name?: string;
  arguments?: { code?: string; object?: { script?: string } };
  protocolVersion?: string;
  cursor?: string;
};
type HttpRpcRequest = {
  jsonrpc: string;
  id: string | number;
  method: string;
  params: HttpRpcParams;
};
type QueueReply = {
  id: string;
  job: { state: string };
  rpc?: { raw: string };
};
type BrokerTransport = { callTool(...args: unknown[]): Promise<unknown> };
type Broker = { close(): Promise<void> };
type MutableModuleLoader = {
  _load(
    request: string,
    parent: { filename?: string } | null,
    ...args: unknown[]
  ): unknown;
};

