const { test } = require('node:test');
const assert = require('node:assert/strict');
const { spawnSync } = require('node:child_process');
const path = require('node:path');
const { fillVolume, levelCurve, drainCheck, cleaningAccess } = require('../src/engineering-fluid');
const base = () => ({ schemaVersion: 1, identity: { model: 'fluid-fixture', revision: '1' }, frame: 'tank', assumptions: ['Closed analytic box cavity; fill axis is the declared frame Z; box displacers only.'] });
const near = (a, b, tol = 1e-9) => assert.ok(Math.abs(a - b) < tol, `${a} != ${b}`);
const cavity = () => ({ type: 'box', length: '1 m', width: '1 m', height: '0.5 m' });
const gravity = { direction: { x: 0, y: 0, z: -1 } };
const displacers = () => [
  { id: 'd1', length: '0.4 m', width: '0.4 m', height: '0.2 m', position: { x: '0.2 m', y: '0.2 m', z: '0.1 m' } },
  { id: 'd2', length: '0.4 m', width: '0.4 m', height: '0.2 m', position: { x: '0.3 m', y: '0.3 m', z: '0.1 m' } },
];
const closure = () => ({ closedDomain: true });
function cli(key, data) { return spawnSync(process.execPath, ['bin/fmcad.js', ...key.split(' '), '--data', JSON.stringify(data), '--json'], { cwd: path.join(__dirname, '..'), encoding: 'utf8', env: { ...process.env, FMCAD_BACKEND: 'no-backend' } }); }
test('fill volume: unioned overlapping displacers are never double subtracted, CG and inertia', () => {
  const d = base(); d.cavity = cavity(); d.level = '0.5 m'; d.density = '1000 kg/m3'; d.gravity = gravity; d.displacers = displacers(); d.closure = closure();
  d.minimumVolume = '0.45 m3'; d.maximumVolume = '0.46 m3';
  const r = fillVolume(d); assert.equal(r.status, 'pass');
  near(r.result.grossVolume.value, 0.5);
  near(r.result.displacedUnionVolume.value, 0.046);
  near(r.result.netVolume.value, 0.454);
  near(r.result.liquidMass.value, 454);
  near(r.result.liquidCG.z.value, 0.1204 / 0.454);
  near(r.result.liquidCG.x.value, 0.2385 / 0.454);
  assert.ok(r.result.liquidInertia.ixx.value > 0 && r.result.liquidInertia.ixx.value < 100);
  d.maximumVolume = '0.45 m3'; assert.equal(fillVolume(d).status, 'fail');
  d.maximumVolume = '0.46 m3'; d.minimumVolume = '0.46 m3'; assert.equal(fillVolume(d).status, 'fail');
  const open = base(); open.cavity = cavity(); open.level = '0.5 m'; open.density = '1000 kg/m3'; open.gravity = gravity; open.displacers = displacers();
  open.closure = { closedDomain: false, errors: ['open cavity without caps or seed faces'] };
  const o = fillVolume(open); assert.equal(o.status, 'blocked'); assert.equal(o.result.closureErrors.length, 1); assert.equal(o.result.netVolume, null);
  const noDensity = base(); noDensity.cavity = cavity(); noDensity.level = '0.5 m'; noDensity.gravity = gravity; noDensity.displacers = displacers(); noDensity.closure = closure();
  noDensity.minimumVolume = '0.45 m3';
  const n = fillVolume(noDensity); assert.equal(n.status, 'unknown'); near(n.result.netVolume.value, 0.454); assert.equal(n.result.liquidMass, null);
  const high = base(); high.cavity = cavity(); high.level = '0.6 m'; high.density = '1000 kg/m3'; high.gravity = gravity; high.closure = closure();
  assert.throws(() => fillVolume(high), /exceeds/);
  const tilted = base(); tilted.cavity = cavity(); tilted.level = '0.5 m'; tilted.density = '1000 kg/m3'; tilted.gravity = { direction: { x: 0, y: 1, z: 0 } }; tilted.closure = closure();
  assert.throws(() => fillVolume(tilted), /Z axis/);
  const rotated = base(); rotated.cavity = cavity(); rotated.level = '0.5 m'; rotated.density = '1000 kg/m3'; rotated.gravity = gravity; rotated.closure = closure();
  rotated.displacers = [{ id: 'r1', length: '0.4 m', width: '0.4 m', height: '0.2 m', position: { x: '0.5 m', y: '0.5 m', z: '0.1 m' }, rotation: { roll: '0 deg', pitch: '0 deg', yaw: '45 deg' } }];
  assert.throws(() => fillVolume(rotated), /axis-aligned/);
});
test('level-curve is monotonic with MIN/MAX criteria and closure evidence', () => {
  const d = base(); d.cavity = cavity(); d.density = '1000 kg/m3'; d.gravity = gravity; d.displacers = displacers(); d.closure = closure();
  d.levels = ['0.1 m', '0.2 m', '0.3 m'];
  d.criteria = [{ id: 'pickup', level: '0.2 m', kind: 'minimum', volume: '0.15 m3' }, { id: 'headspace', level: '0.3 m', kind: 'maximum', volume: '0.26 m3' }];
  const r = levelCurve(d); assert.equal(r.status, 'pass'); assert.equal(r.result.monotonic, true);
  near(r.result.curve[0].volume.value, 0.077); near(r.result.curve[1].volume.value, 0.154); near(r.result.curve[2].volume.value, 0.254);
  assert.equal(r.result.criteria[0].status, 'pass'); assert.equal(r.result.criteria[1].status, 'pass');
  d.criteria[0].volume = '0.16 m3';
  assert.equal(levelCurve(d).status, 'fail');
  d.criteria[0].volume = '0.15 m3'; d.criteria[1].volume = '0.25 m3';
  assert.equal(levelCurve(d).status, 'fail');
  d.criteria[1].volume = '0.26 m3';
  d.levels = ['0.2 m', '0.1 m'];
  assert.throws(() => levelCurve(d), /strictly increasing/);
  d.levels = ['0.1 m', '0.2 m', '0.3 m'];
  const open = { ...d, closure: { closedDomain: false, errors: ['no caps'] } };
  assert.equal(levelCurve(open).status, 'blocked');
  delete d.criteria; delete d.displacers;
  const plain = levelCurve(d); assert.equal(plain.status, 'pass'); near(plain.result.curve[1].volume.value, 0.2);
});
test('drain check: outlet low point, raised outlet residual and unreachable drain level', () => {
  const d = base(); d.cavity = cavity(); d.density = '1000 kg/m3'; d.gravity = gravity;
  d.outlet = { position: { x: '0.5 m', y: '0.5 m', z: '0 m' }, diameter: '10 mm' };
  d.drainLevel = '0 m'; d.maximumResidual = '0.001 m3';
  const r = drainCheck(d); assert.equal(r.status, 'pass'); near(r.result.residualVolume.value, 0); assert.equal(r.result.drainStatus, 'pass');
  d.outlet.position.z = '0.05 m'; d.maximumResidual = '0.1 m3';
  const raised = drainCheck(d); assert.equal(raised.status, 'fail'); assert.equal(raised.result.drainStatus, 'fail'); near(raised.result.poolVolume.value, 0.05);
  d.drainLevel = '0.06 m';
  const reachable = drainCheck(d); assert.equal(reachable.status, 'pass'); near(reachable.result.residualVolume.value, 0.06);
  d.drainLevel = '0 m'; d.outlet.position.z = '0 m';
  d.pockets = [{ id: 'p1', volume: '0.01 m3', drains: false }, { id: 'p2', volume: '0.02 m3', drains: true }];
  d.maximumResidual = '0.005 m3';
  assert.equal(drainCheck(d).status, 'fail');
  d.maximumResidual = '0.02 m3';
  const pockets = drainCheck(d); assert.equal(pockets.status, 'pass'); near(pockets.result.residualVolume.value, 0.01);
  assert.equal(pockets.result.pockets[0].countedInResidual, true); assert.equal(pockets.result.pockets[1].countedInResidual, false);
  d.outlet.position.x = '2 m';
  assert.throws(() => drainCheck(d), /outside/);
});
test('cleaning access: tool reach/fit, pocket and slope reports never certify hygiene', () => {
  const d = base(); d.cavity = cavity(); d.gravity = gravity;
  d.tool = { type: 'brush', length: '300 mm', diameter: '50 mm' };
  d.accesses = [{ id: 'a1', at: { x: '0.5 m', y: '0.5 m', z: '0.5 m' }, direction: { x: 0, y: 0, z: -1 }, depth: '200 mm', openingDiameter: '60 mm' }];
  const r = cleaningAccess(d); assert.equal(r.status, 'pass');
  assert.equal(r.result.accesses[0].reach, true); assert.equal(r.result.accesses[0].fits, true);
  d.accesses.push({ id: 'a2', at: { x: '0.1 m', y: '0.1 m', z: '0.5 m' }, direction: { x: 0, y: 0, z: -1 }, depth: '400 mm', openingDiameter: '60 mm' });
  assert.equal(cleaningAccess(d).status, 'fail');
  d.accesses.pop();
  d.accesses[0].openingDiameter = '40 mm';
  assert.equal(cleaningAccess(d).status, 'fail');
  d.accesses[0].openingDiameter = '60 mm';
  d.pockets = [{ id: 'pk', depth: '100 mm', openingDiameter: '60 mm', at: { x: '0.2 m', y: '0.2 m', z: '0.4 m' } }];
  d.slopes = [{ id: 's1', angle: '10 deg', direction: { x: 1, y: 0, z: 0 } }];
  d.maximumSlope = '15 deg';
  const slopes = cleaningAccess(d); assert.equal(slopes.status, 'pass'); assert.equal(slopes.result.slopes[0].status, 'pass');
  assert.equal(slopes.result.pockets[0].toolFits, true);
  d.maximumSlope = '5 deg';
  assert.equal(cleaningAccess(d).status, 'fail');
  d.maximumSlope = '15 deg';
  delete d.tool.length;
  assert.equal(cleaningAccess(d).status, 'unknown');
  d.tool.length = '300 mm'; d.tool.type = 'scraper';
  assert.throws(() => cleaningAccess(d), /tool.type/);
});
test('fluid real CLI variants, bad input and schema', () => {
  const d = base(); d.cavity = cavity(); d.level = '0.5 m'; d.density = '1000 kg/m3'; d.gravity = gravity; d.displacers = displacers(); d.closure = closure();
  d.minimumVolume = '0.45 m3';
  assert.equal(cli('measure fill-volume', d).status, 0);
  const curve = base(); curve.cavity = cavity(); curve.density = '1000 kg/m3'; curve.gravity = gravity; curve.closure = closure(); curve.levels = ['0.1 m', '0.2 m'];
  assert.equal(cli('fluid level-curve', curve).status, 0);
  const drain = base(); drain.cavity = cavity(); drain.density = '1000 kg/m3'; drain.gravity = gravity;
  drain.outlet = { position: { x: '0.5 m', y: '0.5 m', z: '0 m' }, diameter: '10 mm' };
  drain.drainLevel = '0 m'; drain.maximumResidual = '0.001 m3';
  assert.equal(cli('drain check', drain).status, 0);
  const clean = base(); clean.cavity = cavity(); clean.gravity = gravity;
  clean.tool = { type: 'brush', length: '300 mm', diameter: '50 mm' };
  clean.accesses = [{ id: 'a1', at: { x: '0.5 m', y: '0.5 m', z: '0.5 m' }, direction: { x: 0, y: 0, z: -1 }, depth: '200 mm', openingDiameter: '60 mm' }];
  assert.equal(cli('cleaning access', clean).status, 0);
  const open = { ...d, closure: { closedDomain: false, errors: ['ambiguous open cavity'] } };
  const blocked = cli('measure fill-volume', open); assert.equal(blocked.status, 1); assert.equal(JSON.parse(blocked.stdout).status, 'blocked');
  assert.equal(cli('measure fill-volume', { ...d, typo: true }).status, 1);
  const schema = spawnSync(process.execPath, ['bin/fmcad.js', 'drain', 'check', '--schema'], { cwd: path.join(__dirname, '..'), encoding: 'utf8' });
  assert.equal(schema.status, 0, schema.stderr); assert.match(schema.stdout, /outlet/);
});
