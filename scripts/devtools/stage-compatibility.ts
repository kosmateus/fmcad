import * as fs from "node:fs";
import path from "node:path";
import { compatibilityModules } from "./compatibility-modules";
export function stageCompatibility(root: string): void {
  const outputs = compatibilityModules.map((entry) => {
    const compiled = path.join(root, entry.emittedPath);
    if (!fs.statSync(compiled).isFile())
      throw new Error("Missing canonical compatibility target: " + compiled);
    const load = "require(" + JSON.stringify(entry.target) + ")";
    const facade =
      "publicExports" in entry
        ? "const canonical = " +
          load +
          ";\nmodule.exports = {\n" +
          entry.publicExports
            .map(
              (name) =>
                "  " +
                JSON.stringify(name) +
                ": canonical[" +
                JSON.stringify(name) +
                "]",
            )
            .join(",\n") +
          "\n};\n"
        : "module.exports = " + load + ";\n";
    const main =
      "main" in entry
        ? "if (require.main === module) void canonical[" +
          JSON.stringify(entry.main) +
          "]();\n"
        : "";
    return {
      file: path.join(root, entry.publicPath),
      content:
        '"use strict";\n// Generated by stage-compatibility; edit the canonical TypeScript module.\n' +
        facade +
        main,
    };
  });
  // Validate every canonical target before replacing any public entrypoint.
  for (const { file, content } of outputs) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
  }
}
if (require.main === module) {
  if (process.argv.length !== 2)
    throw new Error("stage-compatibility accepts no arguments");
  stageCompatibility(path.resolve(__dirname, "../../.."));
}
