const ALIAS_KEYS = new Set(Object.keys(ALIASES));
const REQUIRED_EXTRA_KEYS = EXTRA_KEYS.filter((key) => !ALIAS_KEYS.has(key));

export type AgentsProjectsCatalog = Readonly<
  Record<AgentsProjectsMessageKey, MessageValue>
>;

export function agentsProjectsCatalogFor(
  locale: LocaleCode,
  base: Readonly<Record<string, MessageValue>>,
): AgentsProjectsCatalog {
  if (locale === "en") return AGENTS_PROJECTS_MESSAGES;
  const source = TRANSLATIONS[locale];
  if (source.length !== REQUIRED_EXTRA_KEYS.length)
    throw new Error(`Invalid agents/projects catalog for ${locale}`);
  const catalog: Record<string, MessageValue> = {};
  for (const [key, alias] of Object.entries(ALIASES) as [
    AgentsProjectsMessageKey,
    (typeof ALIASES)[AgentsProjectsMessageKey],
  ][]) {
    const value = base[alias!.key];
    if (typeof value !== "string")
      throw new Error(`Missing agents/projects alias target: ${alias!.key}`);
    catalog[key] = value;
  }
  REQUIRED_EXTRA_KEYS.forEach((key, index) => {
    catalog[key] = source[index]!;
  });
  for (const key of Object.keys(
    AGENTS_PROJECTS_MESSAGES,
  ) as AgentsProjectsMessageKey[])
    if (catalog[key] === undefined)
      throw new Error(`Missing agents/projects translation: ${locale}.${key}`);
  return catalog as AgentsProjectsCatalog;
}
